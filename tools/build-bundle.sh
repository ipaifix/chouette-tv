#!/usr/bin/env bash
# Concatenate app JS modules (load order matches former index.html script tags)
# into a single file for faster cold start on Tizen TVs.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/app/js/app.bundle.js"
SRC="$ROOT/app/js"
CHECK=false
case "${1:-}" in
  "") ;;
  --check) CHECK=true ;;
  *) echo "Usage: $0 [--check]" >&2; exit 2 ;;
esac

FILES=(
  branding.js
    http.js
    data-jobs.js
  storage.js
  playlist.js
  xtream.js
  epg-xml.js
  epg.js
  player.js
  app-state.js
  dev-settings.js
  catalog.js
  profiles.js
  ui-overlays.js
  epg-panel.js
  browse.js
  home-ui.js
  live-preview.js
  browse-nav.js
  search-ui.js
  settings-ui.js
  exit-ui.js
  favorites.js
  live-favorite-ui.js
  resume.js
  follow.js
  vod-controls.js
  tracks-ui.js
  playback.js
  experience-ui.js
  remote.js
  boot.js
  main.js
)

# Build beside the output and replace it only when every source was read.
TMP="$(mktemp "$SRC/.app.bundle.XXXXXX")"
trap 'rm -f "$TMP"' EXIT
{
  echo "/* TV player bundle — generated by tools/build-bundle.sh — do not edit */"
  for f in "${FILES[@]}"; do
    echo ""
    echo "/* ==== $f ==== */"
    cat "$SRC/$f"
    echo ""
  done
} > "$TMP"

if "$CHECK"; then
  if ! cmp -s "$TMP" "$OUT"; then
    echo "Bundle is out of date. Run ./tools/build-bundle.sh" >&2
    exit 1
  fi
  echo "Bundle matches source modules."
  exit 0
fi

chmod 644 "$TMP"
mv "$TMP" "$OUT"

wc -c "$OUT" | awk '{print "Wrote", $2, "(" $1, "bytes)"}'
